"""M4 B10 / amendment 15: independent export bytes, metadata and browser effects.

Oracle: public filenames/classes/hooks, independently canonicalized language hash,
our own token/asset inputs and agreement with the public resolver. No adapter
implementation, variable naming convention or generated baseline is consulted.
"""

import json
import re
from urllib.parse import unquote

import pytest
from playwright.sync_api import expect

from tests.m2_support import scalar_leaves, token_values
from tests.support import package_asset
from tests.test_versions_assets import bind_font, expected_hash

FILES = {"generic": {"tokens.css", "roles.css"}, "dtcg-tailwind": {"tokens.json", "theme.css"}}


def export(library, identity, adapter, output):
    library.cli("export", identity, "--adapter", adapter, "--out", output, timeout=30)
    assert all((output / name).is_file() for name in FILES[adapter])
    return {str(file.relative_to(output)): file.read_bytes() for file in output.rglob("*") if file.is_file()}


def export_headers(files, reference, adapter):
    versions = set()
    for name, data in files.items():
        if name.startswith("assets/"):
            continue  # Supplied asset bytes must remain byte-identical, including SVG/XML.
        text = data.decode("utf-8")
        if name.endswith(".json"):
            document = json.loads(text)
            metadata = document["$extensions"]["kinbase-design"]
            assert metadata["language"] == reference
            version = metadata["adapter"]
            assert version.startswith(adapter + "@") and len(version) > len(adapter) + 1
            assert document["$description"] == f"Generated by Kinbase Design from {reference} with {version}"
        else:
            # Permit single/multiline CSS or HTML comment headers without pinning
            # their prose beyond the two required source/version identities.
            header = re.match(r"\A\s*(/\*[\s\S]*?\*/|<!--[\s\S]*?-->|[^\n]+)", text)
            assert header and reference in header[1], (name, "Missing language header")
            match = re.search(re.escape(adapter) + r"@([A-Za-z0-9][A-Za-z0-9._+\-]*)", header[1])
            assert match, (name, "Missing versioned adapter header")
            version = adapter + "@" + match[1]
        versions.add(version)
    assert len(versions) == 1, ("Export files disagree on adapter version", versions)
    return versions.pop()


@pytest.mark.parametrize("adapter", ["generic", "dtcg-tailwind"])
def test_export_is_deterministic_versioned_and_packages_bound_originals(library, language, tmp_path, adapter):
    bind_font(library, language, tmp_path)
    # A second, differently colored image binds only as background-image. This
    # catches exporters that package media-slot assets but omit CSS bindings.
    backdrop = b'<svg xmlns="http://www.w3.org/2000/svg" width="20" height="20"><rect width="20" height="20" fill="#a14524"/></svg>'
    package_asset(library, language, "fixture-backdrop", "image", backdrop)
    language["components"]["listing-card"]["properties"]["background-image"] = "asset:fixture-backdrop:primary"
    library.write(language)
    library.validate(language["id"], accepted=True)
    reference = language["id"] + "@" + expected_hash(language)
    first = export(library, language["id"], adapter, tmp_path / "first-export")
    export_headers(first, reference, adapter)
    # The hash/version excludes display-name metadata and JSON serialization.
    # Different output paths must not introduce absolute paths or timestamps.
    language["name"] = "A renamed display label"
    library.path(language["id"]).write_text(json.dumps(language, sort_keys=True, separators=(",", ":")))
    assert language["id"] + "@" + expected_hash(language) == reference
    second = export(library, language["id"], adapter, tmp_path / "elsewhere with spaces" / "second-export")
    assert first == second, "Identical version/adapter inputs produced different export bytes"
    css = "\n".join(data.decode() for name, data in first.items() if name.endswith(".css") and not name.startswith("assets/"))
    urls = {unquote(match.strip().strip("\"'")) for match in re.findall(r"url\(\s*([^)]*?)\s*\)", css)}
    # Every asset in this fixture is bound: vocabulary media slots, the font
    # family token, or the explicit background-image above. Bytes are our oracle.
    for identity, asset in language["assets"].items():
        for variant, details in asset["variants"].items():
            relative = f'assets/{identity}-{variant}.{details["format"]}'
            assert first[relative] == (library.path(language["id"]).parent / "assets" / details["file"]).read_bytes()
            assert any(url.removeprefix("./") == relative for url in urls), ("Packaged asset is unreferenced by exported CSS", relative)
    assert "@font-face" in css
    if adapter == "dtcg-tailwind":
        theme = first["theme.css"].decode()
        assert re.search(r"@theme\s+static\s*\{", theme)
        assert re.search(r"\[data-theme\s*=\s*['\"]light['\"]\s*\]", theme)
        tokens = list(token_values(json.loads(first["tokens.json"])))
        assert tokens
        for name, _, value in tokens:
            assert not any(isinstance(leaf, str) and re.fullmatch(r"\{[^{}]+\}", leaf)
                           for _, leaf in scalar_leaves(value)), ("DTCG export left a token alias uncomputed", name, value)


@pytest.mark.browser
@pytest.mark.browser_timeout(120)
@pytest.mark.parametrize("adapter", ["generic", "dtcg-tailwind"])
def test_export_applies_role_classes_and_hook_treatments_without_compilation(library, language, tmp_path, page, adapter):
    bind_font(library, language, tmp_path)
    language["components"]["listing-card"]["slots"]["price"] = {"properties": {"color": "{color.component}"}}
    language["overrides"] = [{"scope": "listing-card.price@md", "properties": {"color": "{color.wide}"},
                               "reason": "Independently authored responsive export fixture"}]
    library.write(language)
    output = tmp_path / (adapter + "-export")
    export(library, language["id"], adapter, output)
    # Authored markup contains no preview-generator stylesheet or inline style
    # that could accidentally satisfy the resolver assertions without the export.
    html = output / "consumer.html"
    styles = ("tokens.css", "roles.css") if adapter == "generic" else ("theme.css",)
    links = "".join(f'<link rel="stylesheet" href="{name}">' for name in styles)
    html.write_text('''<!doctype html><html lang="en" data-theme="light"><head><meta charset="utf-8">'''
      + links + '''</head><body>
      <p id="role" class="kd-role-body-neutral">An independent role specimen.</p>
      <article data-kd-construct="listing-card"><p id="slot" data-kd-slot="listing-card.price"
       data-kd-role="label" data-kd-emphasis="primary">A generic highlighted value.</p></article>
      </body></html>''')
    for width, breakpoint, expected_color in ((390, None, "rgb(101, 67, 33)"), (768, "md", "rgb(68, 34, 102)")):
        page.set_viewport_size({"width": width, "height": 900})
        page.goto(html.as_uri())
        expect(page.locator("#role")).to_have_css("color", "rgb(18, 52, 86)")
        expect(page.locator("#role")).to_have_css("font-size", "16px")
        expect(page.locator("#role")).to_have_css("line-height", "24px")
        options = ["--breakpoint", breakpoint] if breakpoint else []
        resolved = library.json("resolve", language["id"], "listing-card.price", *options)["properties"]
        assert resolved["color"]["value"] == ("#442266" if breakpoint else "#654321")
        expect(page.locator("#slot")).to_have_css("color", expected_color)
        for property in ("font-size", "font-family", "font-weight"):
            expect(page.locator("#slot")).to_have_css(property, str(resolved[property]["value"]))
        page.wait_for_function("document.fonts.status === 'loaded'", timeout=5000)
        assert page.evaluate('''[...document.fonts].some(f => f.family.replaceAll('"','') === 'Fixture Sans' && f.status === 'loaded')''')
