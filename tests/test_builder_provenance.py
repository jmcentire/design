"""Runtime attribution is retained evidence, not a new export admission gate."""
import json

import kinbase_design
from tests.content_support import content_library, write_content, render_result
from tests.factory_task_support import (prepare_handoff, directive_document, recorder,
    task_cli, submission, assert_invocation)
from tests.m4_support import git, inventory_check, inventory_document, site_repository


def test_generated_outputs_identify_runtime(content_library, language, tmp_path):
    builder = {"name": "Kinbase Design", "version": kinbase_design.__version__}
    label = "Design artifacts generated by Kinbase Design v" + builder["version"]
    for adapter in ("generic", "dtcg-tailwind"):
        output = tmp_path / adapter
        content_library.cli("export", language["id"], "--adapter", adapter, "--out", output)
        assert label in (output / "ATTRIBUTION.txt").read_text().splitlines()[0]
        styles = list(output.glob("*.css"))
        assert styles and all(label in path.read_text().splitlines()[0] for path in styles)
        if adapter == "dtcg-tailwind":
            metadata = json.loads((output / "tokens.json").read_text())["$extensions"]["kinbase-design"]
            assert metadata["builder"] == builder
    content, _ = write_content(tmp_path / "content")
    output = tmp_path / "page"
    result = render_result(content_library, content, output)
    assert result["builder"] == builder
    assert "<!-- " + label in (output / "index.html").read_text()
    assert label in (output / "ATTRIBUTION.txt").read_text().splitlines()[0]
    assert all(label in path.read_text().splitlines()[0] for path in output.glob("*.css"))


def test_apply_and_later_factory_submission_retain_generation_identity(library, language, tmp_path, monkeypatch):
    from kinbase_design.export.factory import submit

    case = prepare_handoff(library, language, tmp_path)
    path = case.bundle / "handoff.json"
    retained = path.read_bytes()
    builder = {"name": "Kinbase Design", "version": kinbase_design.__version__}
    assert json.loads(retained)["builder"] == builder
    label = "Design artifacts generated by Kinbase Design v" + builder["version"]
    assert label in (case.bundle / "TASK.md").read_text()
    assert label in git(case.repo, "log", "-1", "--format=%B", case.commit)
    monkeypatch.setattr(kinbase_design, "__version__", "999.0.0")
    result = submit(library.library, library.workspace, case.handoff, "later-runtime", dry_run=True)
    assert result["invoked"] is False
    text, directive, _ = directive_document(case.bundle / "directive.md")
    for record in (result, directive):
        assert record["builder"] == builder
        assert record["builder_status"] == "consistent"
    assert "999.0.0" not in text
    assert path.read_bytes() == retained


def test_conflicting_retained_identity_is_reported_without_rewriting(library, language, tmp_path):
    case = prepare_handoff(library, language, tmp_path)
    path = case.bundle / "handoff.json"
    record = json.loads(path.read_text())
    record["builder"]["version"] = "999.0.0"
    changed = json.dumps(record).encode()
    path.write_bytes(changed)
    result = json.loads(task_cli(case, "conflicting-builder", dry=True).stdout)
    text, directive, _ = directive_document(case.bundle / "directive.md")
    for value in (result, directive):
        assert value["builder"] is None
        assert value["builder_status"] == "conflicting"
    assert "unknown" in text.lower()
    assert path.read_bytes() == changed


def test_legacy_handoff_submits_with_unknown_builder(library, language, tmp_path):
    case = prepare_handoff(library, language, tmp_path)
    path = case.bundle / "handoff.json"
    record = json.loads(path.read_text())
    record.pop("builder")
    legacy = json.dumps(record).encode()
    path.write_bytes(legacy)
    spy = recorder(tmp_path / "entrypoint")
    result = task_cli(case, "legacy-builder", factory=spy.path)
    receipt = submission(case, result, "legacy-builder", invoked=True, exit_code=0)
    assert_invocation(case, spy, receipt, "legacy-builder")
    text, directive, _ = directive_document(case.bundle / "directive.md")
    for value in (receipt, directive):
        assert value["builder"] is None
        assert value["builder_status"] == "unknown"
    assert "unknown" in text.lower()
    assert path.read_bytes() == legacy


def test_mixed_export_and_apply_directories_preserve_unrelated_files(library, language, tmp_path):
    output = tmp_path / "export"
    output.mkdir()
    user_file = output / "user.txt"
    user_file.write_text("User-owned note")
    for adapter in ("generic", "dtcg-tailwind"):
        library.cli("export", language["id"], "--adapter", adapter, "--out", output)
    assert user_file.read_text() == "User-owned note"
    assert (output / "roles.css").is_file() and (output / "tokens.json").is_file()
    repo = site_repository(tmp_path)
    inventory_check(library, repo, inventory_document(), accepted=True)
    extra = repo / "design" / "theme" / "user.css"
    extra.parent.mkdir(parents=True)
    extra.write_text("/* User-owned stylesheet */")
    git(repo, "add", ".")
    git(repo, "commit", "-m", "Existing target content")
    original_head = git(repo, "rev-parse", "HEAD")
    result = library.json("apply", language["id"], "--site", repo, "--adapter", "generic",
                          "--target-dir", "design/theme", "--branch")
    assert git(repo, "show", result["branch"]["commit"] + ":design/theme/user.css") == extra.read_text()
    assert git(repo, "rev-parse", "HEAD") == original_head
    assert git(repo, "status", "--porcelain") == ""
