"""Deterministic target adapters over the shared token and CSS computations."""
import json
import re
from copy import deepcopy
from dataclasses import dataclass
from ..builder import current_builder, builder_label
from ..language.tokens import ALIAS, Tokens
from ..language.properties import property_value, LAYOUT_PROPERTIES
from ..render.styles import stylesheet


def custom_property(path):
    # Escape separators injectively, including segments starting/ending in hyphens.
    return '--kd-' + '-'.join(part.replace('_', '_u').replace('-', '_h') for part in path.split('.'))


def metadata(reference, adapter, builder=None):
    builder = current_builder() if builder is None else builder
    return {'$description': f'Generated by Kinbase Design from {reference} with {adapter}',
            '$extensions': {'kinbase-design': {'language': reference, 'adapter': adapter, 'builder': builder}}}


def header(reference, adapter, builder=None):
    builder = current_builder() if builder is None else builder
    return '/* ' + metadata(reference, adapter, builder)['$description'] + '; ' + builder_label(builder) + ' */\n'


def token_declarations(document, variables):
    tokens = Tokens(document['style'])
    declarations = [f'  {variables[name]}: {tokens.evaluate(name)[1]};' for name in sorted(tokens.nodes)]
    for asset, entry in sorted(document.get('assets', {}).items()):
        for variant, detail in sorted(entry['variants'].items()):
            declarations.append(f'  --kd--asset-{custom_property(asset).removeprefix("--kd-")}-{custom_property(variant).removeprefix("--kd-")}: url("assets/{asset}-{variant}.{detail["format"]}");')
    return '\n'.join(declarations) + '\n'


def role_styles(document, vocabulary, variables):
    tokens = Tokens(document['style'])
    classes = []
    for role, entries in sorted(document['roles'].items()):
        for emphasis, properties in sorted(entries.items()):
            declarations = []
            for name, raw in sorted(properties.items()):
                if name == 'surface':continue
                alias = ALIAS.fullmatch(raw) if isinstance(raw, str) else None
                value = 'var(' + variables[alias[1]] + ')' if alias and name not in LAYOUT_PROPERTIES else property_value(document, tokens, name, raw)
                declarations.append(f'{name}:{value}')
            classes.append(f'.kd-role-{role}-{emphasis}' + '{' + ';'.join(declarations) + '}')
    # Renderer identity includes the editable name. Export identity is only id/hash/adapter.
    css = stylesheet(document, vocabulary, variables).split('\n', 1)[1]
    return '\n'.join(classes) + '\n' + css


def computed_tokens(document):
    """Preserve DTCG composite types while removing aliases, including gradient stops."""
    tokens = Tokens(document['style'])

    def value(name):
        node = tokens.nodes[name]
        raw = node['$value']
        alias = ALIAS.fullmatch(raw) if isinstance(raw, str) else None
        if alias:return value(alias[1])
        kind, normalized = tokens.evaluate(name)
        if kind == 'color':
            channels = [int(normalized[i:i+2], 16)/255 for i in (1,3,5)]
            return {'colorSpace': 'srgb', 'components': channels,
                    'alpha': int(normalized[7:9], 16)/255 if len(normalized)==9 else 1}
        if kind in {'dimension', 'duration'}:
            match = re.fullmatch(r'(-?[\d.]+)(px|rem|ms|s)', normalized)
            return {'value': float(match[1]), 'unit': match[2]}
        if kind == 'fontFamily':return [raw] if isinstance(raw,str) else deepcopy(raw)
        if kind == 'gradient':
            stops = []
            for stop in raw:
                color = stop['color']; ref = ALIAS.fullmatch(color) if isinstance(color,str) else None
                if ref:color = value(ref[1])
                else:
                    # The same evaluator validates literal and aliased colors.
                    literal = {'style': {'literal': {'$type': 'color', '$value': color}}}
                    color = computed_tokens(literal)['literal']['$value']
                stops.append({'color': color, 'position': stop['position']})
            return stops
        if kind == 'shadow':
            result={}
            for field,item in raw.items():
                ref=ALIAS.fullmatch(item) if isinstance(item,str) else None
                if ref:result[field]=value(ref[1])
                else:
                    literal={'style':{'literal':{'$type':'color' if field=='color' else 'dimension','$value':item}}}
                    result[field]=computed_tokens(literal)['literal']['$value']
            return result
        return normalized

    output = {}
    for name, node in sorted(tokens.nodes.items()):
        branch = output
        parts = name.split('.')
        for part in parts[:-1]:branch = branch.setdefault(part, {})
        branch[parts[-1]] = {'$type': node['$type'], '$value': value(name)}
    return output


def tailwind_name(path, node):
    """Replace recognized token groups with their Tailwind namespace once."""
    kind = node['$type']; parts = path.split('.'); group = parts[0]
    prefix = {'color':'color', 'fontFamily':'font', 'fontWeight':'font-weight'}.get(kind)
    if kind == 'dimension':
        prefix = {'breakpoint':'breakpoint', 'space':'spacing', 'spacing':'spacing',
                  'size':'text', 'font-size':'text', 'type':'text', 'text':'text',
                  'radius':'radius'}.get(group, 'spacing')
    groups = {'color':{'color'}, 'font':{'font','fontFamily','font-family'},
              'font-weight':{'font','fontWeight','font-weight'}, 'breakpoint':{'breakpoint'},
              'spacing':{'space','spacing'}, 'text':{'size','font-size','type','text'}, 'radius':{'radius'}}
    if len(parts)>1 and group in groups.get(prefix,set()):parts=parts[1:]
    return '--' + (prefix or 'kd-token') + '-' + custom_property('.'.join(parts)).removeprefix('--kd-')


def tailwind_variables(tokens):
    variables={name:tailwind_name(name,node) for name,node in tokens.nodes.items()}
    paths={}
    for name,variable in variables.items():paths.setdefault(variable,[]).append(name)
    for variable,names in paths.items():
        if len(names)<2:continue
        # Group aliases or ungrouped tokens can share a short name. The reserved
        # _path marker cannot occur in escaped segments; retain every token.
        for name in names:
            variables[name]=variable+'-_path-'+custom_property(name).removeprefix('--kd-')
    return variables


@dataclass(frozen=True)
class Adapter:
    name: str
    version: str = '1'

    def files(self, document, vocabulary, reference, builder=None):
        builder = current_builder() if builder is None else builder
        identity = self.name + '@' + self.version
        prefix = header(reference, identity, builder)
        tokens = Tokens(document['style'])
        variables = {name:custom_property(name) for name in tokens.nodes}
        declarations = token_declarations(document, variables)
        roles = role_styles(document, vocabulary, variables)
        if self.name == 'generic':
            return {'tokens.css': (prefix + ':root{\n' + declarations + '}\n').encode(),
                    'roles.css': (prefix + roles).encode()}
        theme_variables=tailwind_variables(tokens)
        theme = '\n'.join(f'  {theme_variables[name]}: {tokens.evaluate(name)[1]};'
                          for name in sorted(tokens.nodes))
        # Match the design-system's top-level @theme plus explicit light overrides.
        # Ordinary declarations also work when inspected directly without Tailwind compilation.
        css = prefix + '@theme static {\n' + theme + '\n}\n'
        css += ":root,[data-theme='light']{\n" + declarations + theme + '\n}\n' + roles
        dtcg = {**metadata(reference,identity,builder), **computed_tokens(document)}
        return {'tokens.json': (json.dumps(dtcg,ensure_ascii=False,sort_keys=True,indent=2)+'\n').encode(),
                'theme.css': css.encode()}


ADAPTERS = {'generic':Adapter('generic'), 'dtcg-tailwind':Adapter('dtcg-tailwind','2')}
