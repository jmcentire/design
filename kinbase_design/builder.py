"""The producing Design runtime, separate from language and target versions."""
import re
import kinbase_design


def current_builder():
    return {'name': 'Kinbase Design', 'version': kinbase_design.__version__}


def builder_identity(value):
    if (isinstance(value, dict) and value.get('name') == 'Kinbase Design'
            and isinstance(value.get('version'), str)
            and re.fullmatch(r'[0-9][A-Za-z0-9.+-]*', value['version'])):
        return {'name': value['name'], 'version': value['version']}
    return None


def builder_label(value):
    builder = builder_identity(value)
    if builder is None:
        return 'Design artifact generator: unknown'
    return 'Design artifacts generated by ' + builder['name'] + ' v' + builder['version']
